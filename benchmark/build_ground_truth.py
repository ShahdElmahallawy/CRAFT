#!/usr/bin/env python3
"""
Builds deterministic gold records for parser evaluation.

The benchmark queries were generated by filling placeholders into
benchmark/templates/*.txt, so generation is invertible — this recovers the
metadata that was never saved, straight from the query text plus the template.

Two field classes, each checked a different way:

  placeholder fields (src, dst, distance limits, battery, time budget, visit time)
      recovered by regex capture, proven by round-trip: substituting the captured
      values back into the template must reproduce the original nl_query exactly.

  template-constant fields (poi_types + order, category_limits, ordered, objective,
  road_preference)
      recovered by running the repo's existing extractors over the template text,
      proven by two independent implementations agreeing:
        - generate_set1.py::_extract_poi_types / _extract_cat_limits (the generator's own)
        - constraint_checker::required_poi_types / required_cat_limits (the corrected one)

Known divergence: the generator's regex (re.escape(display) + "s?") can't match
"pharmacies"/"libraries", so on algo3 it drops those types and falls back to
{"pharmacy": 1}. constraint_checker fixes this and is treated as ground truth;
both values are stored under _provenance so the delta stays auditable (algo3's
queries were generated under the buggy version, so text and generator belief
genuinely differ there).

Fail-closed: any query that fails a check aborts the whole build — no unverified
record gets written.

Usage:
  conda run -n myenv python benchmark/build_ground_truth.py --report
  conda run -n myenv python benchmark/build_ground_truth.py --check-only
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import re
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

TEMPLATES_DIR = ROOT / "benchmark" / "templates"
OUT_DIR = ROOT / "benchmark" / "ground_truth"

# placeholder patterns
PH = re.compile(r"(\{[A-Z0-9_]+\})")
# capture the FULL substituted text (incl. a '%' that lives inside the value —
# the generator writes CURRENT_BATTERY_PCT as f"{pct}%") so re-rendering is lossless.
# NB: no trailing \s* — that would swallow the space belonging to the literal tail
# and break the round-trip prefix comparison.
RAW_NUM = r"([-+]?\d+(?:\.\d+)?%?)"
RAW_COORD = r"(\(\s*[-+]?\d+\.\d+\s*,\s*[-+]?\d+\.\d+\s*\))"
COORD_ONLY = re.compile(r"^\(\s*([-+]?\d+\.\d+)\s*,\s*([-+]?\d+\.\d+)\s*\)$")

# objective (a property of the TEMPLATE FAMILY)
# Every variant within a family optimises the same thing, so the objective is a
# family constant, not something to re-derive per variant from prose. Phrase
# matching is kept ONLY as a consistency check (_objective_signals below).
FAMILY_OBJECTIVE: Dict[str, str] = {
    "ev_routing":     "minimize_distance",
    "ordered_poi":    "minimize_distance",
    "ev+ordered_poi":       "minimize_distance",
    "ordered+time_budget":  "minimize_distance",
    "set3_ordered+desc":    "minimize_distance",
    "unordered_poi":        "minimize_travel_time",
    "poi+road_pref":        "minimize_travel_time",
    "ev+time":              "minimize_travel_time",
    # user decision: algo3 variants state BOTH goals; the collection goal is primary.
    "poi_collection": "maximize_poi",
}

# "shortest travel time" / "shortest trip time" are TIME goals that merely start
# with the word "shortest". Collapse them BEFORE looking for distance wording —
# missing this mislabelled unordered_poi #4 and #13 as minimize_distance.
TIME_QUALIFIED = re.compile(r"shortest\s+(?:total\s+)?(?:travel|trip)?\s*time")
TIME_PHRASES = ["fastest", "quickest", "as quickly as possible", "lowest travel time",
                "trip time as low as possible", "time-wise", "least time", "as fast"]
DIST_PHRASES = ["shortest", "as short as possible", "short route", "least distance"]

# ordered-ness is a property of the template FAMILY, never of prose phrasing —
# unordered_poi expresses unorderedness 11 different ways ("in any order",
# "order flexible", "in whatever order is fastest", ...), so never key on words.
FAMILY_ORDERED: Dict[str, Optional[bool]] = {
    "ordered_poi": True,
    "ev+ordered_poi": True,
    "ordered+time_budget": True,
    "unordered_poi": False,
    "poi_collection": False,
    "poi+road_pref": False,
    "ev_routing": None,   # no POI stops at all
    "ev+time": None,
}

QUERY_SETS = [
    ("set1_ev_routing",    "ev_routing",    "socal_queries/set1/ev_routing.json"),
    ("set1_ordered_poi",   "ordered_poi",   "socal_queries/set1/ordered_poi.json"),
    ("set1_poi_collection","poi_collection","socal_queries/set1/poi_collection.json"),
    ("set1_ev+ordered_poi",      "ev+ordered_poi",      "socal_queries/set1/ev+ordered_poi.json"),
    ("set1_unordered_poi",       "unordered_poi",       "socal_queries/set1/unordered_poi.json"),
    ("set2_ev_routing_ca", "ev_routing",    "california_queries/set2/ev_routing.json"),
    ("poi_road_pref",            "poi+road_pref",       "socal_queries/poi_road_pref/poi_road_pref.json"),
]
SET3_META = ROOT / "benchmark" / "socal_queries" / "set3_descriptions" / "set3_meta.json"


class GroundTruthError(RuntimeError):
    """Raised on any verification failure — the build emits nothing."""


# extractors (both existing implementations)

def load_generator_module():
    """Import generate_set1.py read-only via importlib — the same sibling-import
    pattern run_llmap.py uses for LLMAP's HIPP.py."""
    path = ROOT / "benchmark" / "socal_queries" / "set1" / "generate_set1.py"
    spec = importlib.util.spec_from_file_location("gen_set1_ro", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["gen_set1_ro"] = mod
    spec.loader.exec_module(mod)
    return mod


# template parsing / inversion

def parse_variants(text: str) -> Dict[int, str]:
    out: Dict[int, str] = {}
    for line in text.splitlines():
        m = re.match(r"^(\d+):\s*(.+)$", line.strip())
        if m:
            out[int(m.group(1))] = m.group(2).strip()
    return out


def load_variants(path: Path) -> Dict[int, str]:
    return parse_variants(path.read_text())


def load_committed_variants(rel_path: str) -> Dict[int, str]:
    """The template as committed at git HEAD.

    If a template gets edited after its queries were generated, those queries still
    reflect the old wording. A query that matches no current variant is retried
    against this committed version instead of silently mismatching or failing;
    whichever version actually matched gets recorded in _provenance. Matching
    neither still aborts the build."""
    import subprocess
    try:
        txt = subprocess.check_output(["git", "show", f"HEAD:{rel_path}"],
                                      cwd=ROOT, text=True, stderr=subprocess.DEVNULL)
    except Exception:
        return {}
    return parse_variants(txt)


def compile_variant(text: str) -> Tuple[re.Pattern, List[str], str]:
    """Regex covering the template UP TO AND INCLUDING its last placeholder, the
    placeholder order, and the remaining literal tail (compared separately, because
    the generator sometimes truncates it)."""
    toks = PH.split(text)
    idxs = [i for i, tok in enumerate(toks) if PH.fullmatch(tok)]
    last = idxs[-1] if idxs else -1
    parts, order = [], []
    for tok in toks[:last + 1]:
        if PH.fullmatch(tok):
            name = tok[1:-1]
            order.append(name)
            parts.append(RAW_COORD if name in ("SRC_NODE", "DST_NODE") else RAW_NUM)
        else:
            parts.append(re.escape(tok))
    tail = "".join(toks[last + 1:])
    return re.compile(r"^\s*" + "".join(parts)), order, tail


def invert(nl: str, compiled: Dict[int, Tuple]) -> Tuple[int, Dict[str, str], str, int]:
    """Best-matching variant. Returns (variant_id, raw_values, roundtrip_kind, n_ties)."""
    best, best_score, ties = None, -1, 0
    for vid, (rx, order, tail) in compiled.items():
        m = rx.match(nl)
        if not m:
            continue
        qtail = nl[m.end():]
        # The generator may DROP the template's trailing sentence, or truncate a
        # trailing clause and close it with a period. Anything else = wrong variant.
        if not (tail.startswith(qtail) or qtail.startswith(tail)
                or tail.startswith(qtail.rstrip(" ."))):
            continue
        common = 0
        for a, b in zip(tail, qtail):
            if a != b:
                break
            common += 1
        score = m.end() + common
        if score > best_score:
            best, best_score, ties = (vid, m, order), score, 0
        elif score == best_score:
            ties += 1
    if best is None:
        return None
    vid, m, order = best
    raw = {name: val for name, val in zip(order, m.groups())}
    return vid, raw, "", ties


def roundtrip(template: str, raw: Dict[str, str], nl: str) -> str:
    """Re-render the template from the captured RAW substrings. Returns 'exact',
    'truncated_prefix', or raises."""
    rendered = template
    for name, val in raw.items():
        rendered = rendered.replace("{" + name + "}", val, 1)
    if rendered == nl:
        return "exact"
    if rendered.startswith(nl.rstrip(" .")):
        return "truncated_prefix"
    raise GroundTruthError(
        f"round-trip FAILED\n  rendered={rendered!r}\n  original={nl!r}")


# template-constant classification

def _objective_signals(text: str) -> Tuple[List[str], List[str]]:
    """(time_hits, distance_hits) with time-qualified 'shortest ... time' collapsed
    first, so it is never miscounted as a distance goal."""
    low = TIME_QUALIFIED.sub(" <timegoal> ", text.lower())
    time_hits = [p for p in TIME_PHRASES if p in low]
    if "<timegoal>" in low:
        time_hits.append("shortest travel/trip time")
    dist_hits = [p for p in DIST_PHRASES if p in low]
    return time_hits, dist_hits


def family_objective(family: str, text: str) -> Tuple[str, str]:
    """The objective is a FAMILY constant. Prose is used only to CHECK it — a variant
    whose wording contradicts its family's objective is a hard failure."""
    try:
        obj = FAMILY_OBJECTIVE[family]
    except KeyError:
        raise GroundTruthError(f"no objective configured for family {family!r}")
    time_hits, dist_hits = _objective_signals(text)
    if obj == "minimize_travel_time" and dist_hits and not time_hits:
        raise GroundTruthError(
            f"{family}: family objective is travel_time but variant reads as distance "
            f"({dist_hits}): {text!r}")
    if obj == "minimize_distance" and time_hits and not dist_hits:
        raise GroundTruthError(
            f"{family}: family objective is distance but variant reads as time "
            f"({time_hits}): {text!r}")
    evidence = ";".join(time_hits + dist_hits) or "-"
    return obj, evidence


def family_road_preference(family: str, text: str) -> Optional[str]:
    """Road preference is a FAMILY constant: only poi+road_pref has one, and all 20 of
    its variants avoid highways (6 different phrasings, 3 of which say 'freeways').
    Prose is used only to CHECK that the constant holds."""
    if family != "poi+road_pref":
        return None
    low = text.lower()
    if not re.search(r"\b(highway|freeway)s?\b", low):
        raise GroundTruthError(f"poi+road_pref variant names no road type: {text!r}")
    if "prefer" in low and "highway" in low:
        raise GroundTruthError(f"poi+road_pref variant reads as PREFER, not avoid: {text!r}")
    return "avoid_highways"


# gold record assembly

def parse_coord(raw: str) -> List[float]:
    m = COORD_ONLY.match(raw.strip())
    if not m:
        raise GroundTruthError(f"bad coordinate: {raw!r}")
    return [float(m.group(1)), float(m.group(2))]


def num(raw: Optional[str]) -> Optional[float]:
    if raw is None:
        return None
    v = float(str(raw).rstrip("%"))
    return v


def build_record(qid: str, nl: str, family: str, vid: int, raw: Dict[str, str],
                 rt_kind: str, consts: Dict[str, Any]) -> Dict[str, Any]:
    # explicit numbered leg limits, in order
    legs = []
    for i in (1, 2, 3):
        key = f"DISTANCE_LIMIT_{i}_MI"
        if key in raw:
            legs.append(num(raw[key]))
    shared = "DISTANCE_LIMIT_MI" in raw
    if shared and not legs:
        # a single shared per-leg limit. Store the value + the flag; do NOT expand
        # to a leg count here — how many legs a query has (does the final leg to the
        # destination count?) is exactly the interpretation the parser is being
        # evaluated on, so gold must not prejudge it.
        legs = [num(raw["DISTANCE_LIMIT_MI"])]

    rec = {
        "query_id": qid,
        "template": family,
        "template_variant": vid,
        "src_latlon": parse_coord(raw["SRC_NODE"]) if "SRC_NODE" in raw else None,
        "dst_latlon": parse_coord(raw["DST_NODE"]) if "DST_NODE" in raw else None,
        "objective": consts["objective"],
        "poi_types": consts["poi_types"] or None,
        "ordered": consts["ordered"],
        "leg_distance_limits_mi": legs or None,
        "shared_leg_limit": shared or None,
        "category_limits": consts["category_limits"],
        # explicit None checks, not `or` — a 0 budget must not silently fall through
        "time_budget_min": (num(raw["TIME_BUDGET_MIN"]) if "TIME_BUDGET_MIN" in raw
                            else num(raw["TIME_BUDGET_HOURS"]) * 60
                            if "TIME_BUDGET_HOURS" in raw else None),
        "visit_min": num(raw.get("VISIT_MIN")),
        "current_battery_pct": num(raw.get("CURRENT_BATTERY_PCT")),
        "current_battery_mi": num(raw.get("CURRENT_BATTERY_MI")),
        "max_battery_mi": num(raw.get("MAX_BATTERY_MI")),
        "road_preference": consts["road_preference"],
        "poi_filters": None,
        "_provenance": {
            "matched_by": consts["matched_by"],
            "roundtrip": rt_kind,
            "types_generator": consts["types_generator"],
            "types_checker": consts["types_checker"],
            "cat_limits_generator": consts["cat_limits_generator"],
            "cat_limits_checker": consts["cat_limits_checker"],
            "cat_limits_postfix": consts.get("cat_limits_postfix"),
            "objective_evidence": consts["objective_evidence"],
            "template_source": consts.get("template_source", "current"),
        },
    }
    return rec


def postfix_cat_limits(text: str) -> Dict[str, int]:
    """Third extractor: limits written AFTER the noun, which BOTH repo extractors miss.

    algo3 #24 "visiting libraries, up to 2", #27 "some library stops, up to 2",
    #29 "as many supermarket stops as possible, up to 3". Both existing extractors
    look for `<digit> <type>` (or `<type> (max N)`), find nothing, and fall back to a
    bare-mention default of 1 — silently understating an explicitly stated limit.
    """
    low = text.lower()
    out: Dict[str, int] = {}
    for display in ("pharmacy", "bank", "supermarket", "library"):
        plural = (re.escape(display[:-1]) + r"(?:y|ies)" if display.endswith("y")
                  else re.escape(display) + r"(?:s|es)?")
        m = re.search(plural + r"\b[^.;]{0,35}?\bup to\s+(\d+)", low)
        if m:
            out[display] = int(m.group(1))
    return out


def variant_constants(text: str, family: str, gen) -> Dict[str, Any]:
    from evaluation.constraint_checker import required_poi_types, required_cat_limits

    g_types = gen._extract_poi_types(text)
    c_types = required_poi_types(text)
    g_lims = gen._extract_cat_limits(text)
    c_lims = dict(required_cat_limits(text))

    # Reconcile: an EXPLICIT post-noun number beats the checker's bare-mention
    # default of 1. A conflict between two explicit numbers is a hard failure.
    p_lims = postfix_cat_limits(text)
    for cat, val in p_lims.items():
        cur = c_lims.get(cat)
        if cur is None or cur == 1:
            c_lims[cat] = val
        elif cur != val:
            raise GroundTruthError(
                f"{family}: conflicting explicit limits for {cat}: "
                f"checker={cur} postfix={val} in {text!r}")

    objective, evidence = family_objective(family, text)
    is_collection = family == "poi_collection"
    return {
        "poi_types": c_types,                      # checker is the corrected impl
        "category_limits": c_lims if is_collection else None,
        "ordered": FAMILY_ORDERED.get(family),
        "objective": objective,
        "objective_evidence": evidence,
        "road_preference": family_road_preference(family, text),
        "types_generator": g_types,
        "types_checker": c_types,
        "cat_limits_generator": g_lims if is_collection else None,
        "cat_limits_checker": c_lims if is_collection else None,
        "cat_limits_postfix": (p_lims or None) if is_collection else None,
        "matched_by": [],
    }


# verification

def check_extractor_agreement(family: str, vid: int, consts: Dict[str, Any]) -> Optional[str]:
    """V4. Compare the generator's extractor against constraint_checker's.

    ORDER is only meaningful for ordered families, so unordered families are
    compared as sets. The generator's y->ies plural bug shows up two ways:
      - a strict SUBSET (it simply missed "pharmacies"/"libraries"), or
      - the same set in a DIFFERENT ORDER, when the singular form happens to occur
        later in the sentence (e.g. algo3's trailing "I'd especially like pharmacy
        stops"), which shifts that type's first-appearance position.
    Both are expected on algo3. Anything else is a hard failure.
    """
    g, c = consts["types_generator"], consts["types_checker"]
    if g == c:
        return None
    ordered = consts["ordered"]
    if ordered:
        raise GroundTruthError(
            f"{family}#{vid}: extractors disagree on an ORDERED family: "
            f"generator={g} checker={c}")
    if set(g) == set(c):
        return f"{family}#{vid}: same set, order differs (plural bug shifts position): {g} vs {c}"
    if set(g) < set(c):
        return f"{family}#{vid}: generator subset (known y->ies plural bug): {g} vs {c}"
    raise GroundTruthError(
        f"{family}#{vid}: extractors disagree in an UNEXPECTED shape: "
        f"generator={g} checker={c}")


def sanity_check(rec: Dict[str, Any]) -> None:
    """V7."""
    for key in ("src_latlon", "dst_latlon"):
        c = rec.get(key)
        if c is None:
            continue
        lat, lon = c
        if not (32.0 <= lat <= 42.5 and -125.0 <= lon <= -114.0):
            raise GroundTruthError(f"{rec['query_id']}: {key} outside California bbox: {c}")
    for v in (rec.get("leg_distance_limits_mi") or []):
        if v is None or v <= 0:
            raise GroundTruthError(f"{rec['query_id']}: non-positive leg limit {v}")
    pct = rec.get("current_battery_pct")
    if pct is not None and not (0 <= pct <= 100):
        raise GroundTruthError(f"{rec['query_id']}: battery pct out of range: {pct}")
    for k in ("time_budget_min", "visit_min", "max_battery_mi"):
        v = rec.get(k)
        if v is not None and v <= 0:
            raise GroundTruthError(f"{rec['query_id']}: non-positive {k}={v}")
    blob = json.dumps(rec)
    if re.search(r"\{[A-Z0-9_]+\}", blob):
        raise GroundTruthError(f"{rec['query_id']}: unfilled placeholder in gold")


def structural_invariant(family: str, text: str, consts: Dict[str, Any]) -> Optional[str]:
    """V5: for families with numbered leg limits, #types must equal #leg placeholders."""
    n_legs = len(set(re.findall(r"\{DISTANCE_LIMIT_(\d+)_MI\}", text)))
    if not n_legs:
        return None
    if len(consts["poi_types"]) != n_legs:
        raise GroundTruthError(
            f"{family}: #types={len(consts['poi_types'])} != #leg placeholders={n_legs}")
    return None


# set3 conversion (already has real gold; no inversion needed)

def convert_set3() -> List[Dict[str, Any]]:
    meta = json.loads(SET3_META.read_text())
    queries = {q["query_id"]: q["nl_query"] for q in json.loads(
        (ROOT / "benchmark/socal_queries/set3_descriptions/ordered+desc.json").read_text())}
    out = []
    for r in meta:
        qid = r["query_id"]
        objective, evidence = family_objective("set3_ordered+desc", queries.get(qid, ""))
        out.append({
            "query_id": qid,
            "template": "set3_ordered+desc",
            "template_variant": None,
            "src_latlon": list(r["src"]),
            "dst_latlon": list(r["dst"]),
            "objective": objective,
            "poi_types": r.get("poi_types"),
            "ordered": True,
            "leg_distance_limits_mi": r.get("distance_limits_mi"),
            "shared_leg_limit": None,
            "category_limits": None,
            "time_budget_min": None,
            "visit_min": None,
            "current_battery_pct": None,
            "current_battery_mi": None,
            "max_battery_mi": None,
            "road_preference": None,
            "poi_filters": r.get("poi_filters"),
            "_provenance": {
                "matched_by": ["set3_meta.json"],
                "roundtrip": "n/a (real gold saved at generation time)",
                "types_generator": None, "types_checker": None,
                "cat_limits_generator": None, "cat_limits_checker": None,
                "objective_evidence": evidence,
                "stops": r.get("stops"),
            },
        })
    return out


# main

def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def source_hashes() -> Dict[str, Dict[str, str]]:
    return {
        "template_sha": {p.name: sha(p) for p in sorted(TEMPLATES_DIR.glob("*.txt"))},
        "query_file_sha": {n: sha(ROOT / "benchmark" / r) for n, _, r in QUERY_SETS},
        "set3_meta_sha": {"set3_meta.json": sha(SET3_META)},
        "extractor_sha": {
            "generate_set1.py": sha(ROOT / "benchmark/socal_queries/set1/generate_set1.py"),
            "constraint_checker.py": sha(ROOT / "evaluation/constraint_checker.py"),
        },
    }


def check_source_hashes(out_dir: Path, force: bool = False) -> List[str]:
    """V10 — ENFORCED, not merely recorded. If a template / query file / extractor
    changed since the last build, existing gold is stale: fail loudly instead of
    silently emitting different ground truth."""
    manifest_path = out_dir / "manifest.json"
    if not manifest_path.exists():
        return []
    old = json.loads(manifest_path.read_text())
    new = source_hashes()
    drift: List[str] = []
    for section, values in new.items():
        prev = old.get(section) or {}
        if section == "set3_meta_sha" and isinstance(prev, str):
            prev = {"set3_meta.json": prev}          # tolerate the older manifest shape
        for name, digest in values.items():
            if name in prev and prev[name] != digest:
                drift.append(f"{section}/{name}: {prev[name]} -> {digest}")
    if drift and not force:
        raise GroundTruthError(
            "source files changed since the last build — existing gold is STALE:\n  "
            + "\n  ".join(drift)
            + "\nRe-run with --force to regenerate against the new sources.")
    return drift


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", default=str(OUT_DIR))
    ap.add_argument("--report", action="store_true", help="print the per-variant table")
    ap.add_argument("--check-only", action="store_true", help="verify but write nothing")
    ap.add_argument("--force", action="store_true",
                    help="regenerate even though source files changed since last build")
    args = ap.parse_args()

    out_dir = Path(args.out_dir)
    # V10 FIRST: if a source changed, say so plainly. Running it later meant a stale
    # template surfaced as a confusing "no template variant matched" from V1 instead.
    drift = check_source_hashes(out_dir, force=args.force)
    if drift:
        print("[warn] sources changed since the last build (--force given):")
        for d in drift:
            print(f"       {d}")
    gen = load_generator_module()

    all_gold: Dict[str, List[Dict[str, Any]]] = {}
    stale_report: List[str] = []
    variant_consts: Dict[str, Dict[str, Any]] = {}
    notes: List[str] = []
    stats = {"exact": 0, "truncated_prefix": 0, "id_agree": 0, "id_checked": 0}

    for set_name, family, rel in QUERY_SETS:
        qpath = ROOT / "benchmark" / rel
        tpath = TEMPLATES_DIR / f"{family}.txt"
        variants = load_variants(tpath)
        compiled = {i: compile_variant(t) for i, t in variants.items()}

        # per-variant constants + their verification (V4, V5)
        for vid, text in variants.items():
            key = f"{family}#{vid}"
            if key in variant_consts:
                continue
            consts = variant_constants(text, family, gen)
            note = check_extractor_agreement(family, vid, consts)
            if note:
                notes.append(note)
            structural_invariant(family, text, consts)
            variant_consts[key] = consts

        # fallback for queries generated before an in-place template edit
        committed = load_committed_variants(f"benchmark/templates/{family}.txt")
        compiled_old = {i: compile_variant(t) for i, t in committed.items()
                        if committed.get(i) != variants.get(i)}
        stale_hits: Counter = Counter()

        queries = json.loads(qpath.read_text())
        records = []
        for q in queries:
            qid, nl = q["query_id"], q["nl_query"]
            template_src = "current"
            res = invert(nl, compiled)
            if res is None and compiled_old:
                res = invert(nl, compiled_old)
                if res is not None:
                    template_src = "committed(HEAD)"
                    stale_hits[res[0]] += 1
            if res is None:
                raise GroundTruthError(f"{qid}: no template variant matched")   # V1/V9
            vid, raw, _, ties = res
            if ties:                                                            # V2
                raise GroundTruthError(f"{qid}: {ties+1} variants tie — ambiguous")
            vsrc = variants if template_src == "current" else committed
            rt_kind = roundtrip(vsrc[vid], raw, nl)                            # V1
            stats[rt_kind] += 1

            if template_src == "current":
                consts = dict(variant_consts[f"{family}#{vid}"])
            else:
                consts = variant_constants(committed[vid], family, gen)
                check_extractor_agreement(family, vid, consts)
            consts["template_source"] = template_src
            matched_by = ["regex"]
            m = re.search(r"_(\d+)_v\d+$", qid)                                 # V3
            if m:
                stats["id_checked"] += 1
                if int(m.group(1)) != vid:
                    raise GroundTruthError(
                        f"{qid}: query_id index {m.group(1)} != matched variant {vid}")
                stats["id_agree"] += 1
                matched_by.append("query_id")
            consts["matched_by"] = matched_by

            rec = build_record(qid, nl, family, vid, raw, rt_kind, consts)
            sanity_check(rec)                                                   # V7
            records.append(rec)

        if len({r["query_id"] for r in records}) != len(queries):               # V9
            raise GroundTruthError(f"{set_name}: duplicate or missing query_id")
        all_gold[set_name] = records
        note = ""
        if stale_hits:
            note = (f"  [!] {sum(stale_hits.values())} queries matched the COMMITTED "
                    f"template (variants {sorted(stale_hits)}) — the working-tree "
                    f"template was edited after these queries were generated")
            stale_report.append(f"{set_name}: {dict(stale_hits)}")
        print(f"[ok] {set_name:28s} {len(records):4d} records  (template {family}){note}")

    set3 = convert_set3()
    all_gold["set3_ordered+desc"] = set3
    print(f"[ok] {'set3_ordered+desc':28s} {len(set3):4d} records  (from set3_meta.json)")

    total = sum(len(v) for v in all_gold.values())
    print(f"\n[verify] round-trip: exact={stats['exact']} "
          f"truncated_prefix={stats['truncated_prefix']} (failures abort)")
    print(f"[verify] query_id index agreement: {stats['id_agree']}/{stats['id_checked']}")
    print(f"[verify] extractor notes (expected plural-bug subsets): {len(notes)}")
    print(f"[verify] total gold records: {total}")

    if args.report:
        print("\n--- per-variant constants ---")
        for key in sorted(variant_consts, key=lambda k: (k.split("#")[0], int(k.split("#")[1]))):
            c = variant_consts[key]
            line = (f"  {key:28s} obj={c['objective']:20s} ordered={str(c['ordered']):5s} "
                    f"types={c['poi_types']}")
            if c["category_limits"] is not None:
                line += f" limits={c['category_limits']}"
            if c["road_preference"]:
                line += f" road={c['road_preference']}"
            print(line)
        if notes:
            print("\n--- extractor disagreements (generator plural bug, expected) ---")
            for n in notes:
                print("  " + n)

    if args.check_only:
        print("\n[check-only] all verifications passed; nothing written.")
        return

    out_dir.mkdir(parents=True, exist_ok=True)
    for name, recs in all_gold.items():
        (out_dir / f"{name}_gold.json").write_text(
            json.dumps(recs, indent=2, sort_keys=True) + "\n")

    (out_dir / "variant_constants.json").write_text(
        json.dumps(variant_consts, indent=2, sort_keys=True) + "\n")

    manifest = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "builder_sha": sha(Path(__file__)),
        **source_hashes(),
        "counts": {n: len(r) for n, r in all_gold.items()},
        "total": total,
        "verification": {
            "roundtrip_exact": stats["exact"],
            "roundtrip_truncated_prefix": stats["truncated_prefix"],
            "roundtrip_failures": 0,
            "query_id_index_agreement": f"{stats['id_agree']}/{stats['id_checked']}",
            "extractor_expected_subset_notes": notes,
            "queries_matched_committed_template": stale_report,
        },
        "decisions": {
            "objective": "a FAMILY constant (FAMILY_OBJECTIVE); prose is only a consistency check",
            "road_preference": "a FAMILY constant: poi+road_pref = avoid_highways for all 20 variants",
            "algo3_objective": "maximize_poi (variants state both goals; collection is primary)",
            "poi_types_source": "constraint_checker (generator has a y->ies plural bug)",
        },
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"\n[done] wrote {len(all_gold)} gold files + variant_constants.json + manifest.json")
    print(f"[done] {out_dir}")


if __name__ == "__main__":
    main()
